<?php

namespace App\Console\Commands;

use App\Migration\Woo\StoreApiClient;
use App\Models\Category;
use App\Models\Product;
use App\Models\ProductTranslation;
use App\Models\ProductVariant;
use App\Models\Redirect;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Spatie\MediaLibrary\MediaCollections\Models\Media;

#[Signature('woo:verify {--no-report : Do not write documentation/migration-report.md}')]
#[Description('Compare the WooCommerce source with imported data and write the migration report')]
class WooVerify extends Command
{
    public function handle(): int
    {
        $client = StoreApiClient::fromConfig();

        $sourceIds = [];
        $sourceImages = 0;
        $priceMismatches = [];
        $slugMismatches = [];

        foreach ($client->productPages() as $products) {
            $local = Product::query()->whereIn('source_id', array_column($products, 'id'))
                ->with(['defaultVariant', 'translations'])->get()->keyBy('source_id');

            foreach ($products as $row) {
                $sourceIds[] = (int) $row['id'];
                $sourceImages += count($row['images']);
                $product = $local->get($row['id']);
                if (! $product) {
                    continue;
                }
                if ((int) $row['prices']['regular_price'] !== $product->defaultVariant?->regular_price) {
                    $priceMismatches[] = $row['id'];
                }
                if (rawurldecode($row['slug']) !== $product->translate('ar', false)?->slug) {
                    $slugMismatches[] = $row['id'];
                }
            }
        }

        $imported = Product::query()->whereIn('source_id', $sourceIds)->pluck('source_id')->all();
        $missing = array_values(array_diff($sourceIds, $imported));
        $productMorph = (new Product)->getMorphClass();
        $productsWithoutImage = Product::query()->whereNotNull('source_id')
            ->whereNotExists(fn ($q) => $q->select(DB::raw(1))->from('media')
                ->whereColumn('media.model_id', 'products.id')->where('media.model_type', $productMorph))
            ->count();

        $rows = [
            ['Products', count($sourceIds), count($imported), count($missing) === 0 ? 'OK' : count($missing).' missing'],
            ['Categories', count($client->categories()), Category::query()->whereNotNull('source_id')->count(), ''],
            ['Variants (default)', count($sourceIds), ProductVariant::query()->where('signature', '')->count(), ''],
            ['Images (references)', $sourceImages, Media::query()->where('model_type', $productMorph)->count(), "{$productsWithoutImage} products without image"],
            ['Regular price mismatches', 0, count($priceMismatches), $priceMismatches ? 'CHECK' : 'OK'],
            ['Arabic slug mismatches', 0, count($slugMismatches), $slugMismatches ? 'CHECK' : 'OK'],
            ['English translations', '-', ProductTranslation::query()->where('locale', 'en')->count(), 'derived from bilingual names'],
            ['Hebrew translations', '-', ProductTranslation::query()->where('locale', 'he')->count(), 'none in source → fallback en→ar'],
            ['Products with prices = 0', '-', ProductVariant::query()->where('regular_price', 0)->count(), ''],
            ['Legacy redirects', '-', Redirect::query()->count(), '/en/... TranslatePress URLs'],
        ];

        $this->table(['Check', 'Source', 'Local', 'Status'], $rows);

        if (! $this->option('no-report')) {
            $this->writeReport($rows, $missing, $priceMismatches, $slugMismatches);
            $this->components->info('Wrote documentation/migration-report.md');
        }

        return $missing === [] && $priceMismatches === [] ? self::SUCCESS : self::FAILURE;
    }

    private function writeReport(array $rows, array $missing, array $prices, array $slugs): void
    {
        $md = "# Migration Report\n\nGenerated by `php artisan woo:verify` on ".now()->toDateTimeString()." against the public Store API.\n\n";
        $md .= "| Check | Source | Local | Status |\n|---|---|---|---|\n";
        foreach ($rows as $r) {
            $md .= '| '.implode(' | ', $r)." |\n";
        }
        $md .= "\n## Discrepancies\n";
        $md .= '- Missing products (source ids): '.($missing ? implode(', ', $missing) : 'none')."\n";
        $md .= '- Price mismatches: '.($prices ? implode(', ', $prices) : 'none')."\n";
        $md .= '- Slug mismatches: '.($slugs ? implode(', ', $slugs) : 'none')."\n";
        $md .= "\n## Known limitations\n- Store API exposes only published, visible products; drafts/private items and wholesale prices need DB or `wc/v3` access.\n";
        $md .= "- English descriptions live in TranslatePress tables (not exposed) — en/he descriptions fall back to Arabic until DB access.\n";
        $md .= "- Warnings per product (missing/duplicate SKU, no English name): `storage/logs/woo-migration.log`.\n";

        File::put(base_path('documentation/migration-report.md'), $md);
    }
}
